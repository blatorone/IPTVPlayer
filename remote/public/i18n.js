// Texts of the remote settings page in all app languages. Texts that come from the device
// (setting labels, portal and category names, messages) are already translated by the app.
// t(key, ...args): current language, fallback German, then the key itself. {0}, {1} = arguments.

const I18N = {};
const I18N_LANGUAGES = ["de", "en", "tr", "pl", "ru", "ar", "ro", "hr", "bs", "sr", "sr-Latn", "es", "fr", "it", "pt-BR", "sq", "uk"];
let i18nCurrent = "en";

function resolveLanguage(tag) {
  const clean = String(tag || "").trim().replace(/^b\+/i, "").replace(/[_+]/g, "-");
  if (!clean) return "en";
  const lower = clean.toLowerCase();
  for (const code of I18N_LANGUAGES) if (code.toLowerCase() === lower) return code;
  const base = lower.split("-")[0];
  if (base === "sr" && lower.includes("latn")) return "sr-Latn";
  if (base === "pt") return "pt-BR";
  for (const code of I18N_LANGUAGES) if (code.toLowerCase() === base) return code;
  return "en";
}

function t(key, ...args) {
  const table = I18N[i18nCurrent] || {};
  let text = table[key];
  if (text === undefined) text = (I18N.de || {})[key];
  if (text === undefined) return key;
  return text.replace(/\{(\d+)\}/g, (m, i) => (args[Number(i)] !== undefined ? String(args[Number(i)]) : m));
}

function applyStaticTexts() {
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  // Only our own fixed translations (with <b>) are inserted as HTML, never device data.
  for (const node of document.querySelectorAll("[data-i18n-html]")) node.innerHTML = t(node.dataset.i18nHtml);
  for (const node of document.querySelectorAll("[data-i18n-placeholder]")) node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  for (const node of document.querySelectorAll("[data-i18n-aria]")) node.setAttribute("aria-label", t(node.dataset.i18nAria));
  document.title = t("page.title");
}

function setLanguage(tag) {
  i18nCurrent = resolveLanguage(tag);
  document.documentElement.lang = i18nCurrent;
  const base = i18nCurrent.split("-")[0];
  document.documentElement.dir = base === "ar" || base === "he" || base === "iw" ? "rtl" : "ltr";
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", applyStaticTexts, { once: true });
  else applyStaticTexts();
}

